count_df = long_df.groupby(["Group", "Function_Group"])["Feature"].count().reset_index()
count_df = count_df.rename(columns={"Feature": "Count"})

# === NORMALIZE TO PROPORTIONS ===
total_per_group = count_df.groupby("Group")["Count"].sum().reset_index().rename(columns={"Count": "Total"})
count_df = pd.merge(count_df, total_per_group, on="Group")
count_df["Proportion"] = count_df["Count"] / count_df["Total"] * 100

# === SAVE COMPARISON SUMMARY TABLE ===
pivot = count_df.pivot(index="Function_Group", columns="Group", values="Proportion").fillna(0)
