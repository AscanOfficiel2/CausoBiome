# Step 1: Load & Format Data
# -----------------------
# Expression matrix (long format → transpose)
expr = pd.read_csv("/content/combined_ARG_VFDB_final_DATA.csv", index_col=0)
expr = expr.T  # Now rows = samples, columns = features
expr.index.name = "Sample_ID"
expr.reset_index(inplace=True)

# Metadata and selected features
meta = pd.read_csv("/content/Metadata_Aligned_VF_ARG_CountMatrix.csv")
top_species = pd.read_csv("/content/Filtered_biomarker_annotated.csv")

# -----------------------
# Step 2: Prepare for Merge
# -----------------------
species_list = top_species['Feature'].tolist()
expr_filtered = expr[['Sample_ID'] + [f for f in species_list if f in expr.columns]]

# Merge metadata and expression
meta["Sample_ID"] = meta["Sample_ID"].astype(str)
expr_filtered["Sample_ID"] = expr_filtered["Sample_ID"].astype(str)
merged = pd.merge(meta, expr_filtered, on="Sample_ID", how="inner")

# Encode labels
merged['OrdinalOutcome'] = merged['Group'].map({'Healthy': 0, 'Adenoma': 1, 'Cancer': 2})
merged['Sex'] = merged['Sex'].map({'female': 0, 'male': 1})

Y = merged['OrdinalOutcome'].values
X = merged[['Age', 'BMI', 'Sex']].values

# -----------------------
# Step 3: Causal Estimation
# -----------------------
results = []
for species in species_list:
    if species not in merged.columns:
        continue

    print(f"Estimating for species: {species}")
    T = merged[[species]].values

    dml_model = LinearDML(
        model_y=RandomForestRegressor(n_estimators=100, random_state=42),
        model_t=RandomForestRegressor(n_estimators=100, random_state=42),
        discrete_treatment=False,
        random_state=42
    )

    dml_model.fit(Y, T, X=X)
    treatment_effects = dml_model.effect(X)
    ate = np.mean(treatment_effects)
    conf_int = dml_model.effect_interval(X)

    results.append({
        'Species': species,
        'ATE': ate,
        'CI Lower': np.mean(conf_int[0]),
        'CI Upper': np.mean(conf_int[1])
    })

# -----------------------
# Step 4: Save Results
# -----------------------
results_df = pd.DataFrame(results)
print("\n✅ DML Causal Effect Estimation Completed")
print(results_df)

