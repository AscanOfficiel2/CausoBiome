# === Read Uploaded Data ===
meta = pd.read_csv("Metadata_Aligned_VF_ARG_CountMatrix.csv")
matrix = pd.read_csv("combined_ARG_VFDB_final_DATA.csv", index_col=0).T
biomarkers = pd.read_csv("/content/Filtered_biomarker_annotated.csv")

# === Format ===
meta["Sample_ID"] = meta["Sample_ID"].astype(str)
matrix.index.name = "Sample_ID"
matrix.reset_index(inplace=True)
merged = pd.merge(matrix, meta, on="Sample_ID", how="inner")

# === Biomarkers & Log2 Transform ===
top_features = biomarkers["Feature"].tolist()
log_data = np.log2(merged[top_features] + 1)
log_data["Group"] = merged["Group"]

# === Comparisons ===
comparisons = [("Cancer", "Healthy"), ("Adenoma", "Healthy"), ("Cancer", "Adenoma")]
fc_matrix = pd.DataFrame(index=top_features)
pval_matrix = pd.DataFrame(index=top_features)
all_results = []

# === Compute log2FC + MWU Test ===
for group_a, group_b in comparisons:
    log2fc_list = []
    pval_list = []
    for gene in top_features:
        data_a = log_data[log_data["Group"] == group_a][gene]
        data_b = log_data[log_data["Group"] == group_b][gene]
        stat, p = mannwhitneyu(data_a, data_b, alternative="two-sided")
        log2fc = data_a.mean() - data_b.mean()
        log2fc_list.append(log2fc)
        pval_list.append(p)
        all_results.append({
            "Biomarker": gene,
            "Comparison": f"{group_a} vs {group_b}",
            "log2FC": log2fc,
            "p-value": p
        })
    fc_matrix[f"{group_a} vs {group_b}"] = log2fc_list
    pval_matrix[f"{group_a} vs {group_b}"] = pval_list

# === Adjust p-values ===
for comp in pval_matrix.columns:
    _, fdr, _, _ = multipletests(pval_matrix[comp], method="fdr_bh")
    pval_matrix[comp] = fdr

# === Export Results ===
results_df = pd.DataFrame(all_results)
results_df["FDR"] = results_df.groupby("Comparison")["p-value"].transform(lambda p: multipletests(p, method="fdr_bh")[1])
results_df["-log10(FDR)"] = -np.log10(results_df["FDR"] + 1e-10)

