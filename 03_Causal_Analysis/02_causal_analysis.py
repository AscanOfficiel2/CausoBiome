biomarkers = biomarker_df["Feature"].dropna().unique().tolist()

# === Validate and filter features present in the matrix ===
available_features = [f for f in biomarkers if f in expr.columns]
print(f"✅ {len(available_features)} of {len(biomarkers)} features found in expression matrix.")

# === Filter expression to valid features + Sample_ID ===
expr_filtered = expr[["Sample_ID"] + available_features]
merged = pd.merge(meta, expr_filtered, on="Sample_ID", how="inner")

# === Encode outcome and confounders ===
merged['OrdinalOutcome'] = merged['Group'].map({'Healthy': 0, 'Adenoma': 1, 'Cancer': 2})
merged['Sex'] = merged['Sex'].map({'female': 0, 'male': 1})

Y = merged['OrdinalOutcome'].values
X = merged[['Age', 'BMI', 'Sex']].values

# === Loop over pairs ===
interaction_results = []

for sp1, sp2 in combinations(available_features, 2):
    print(f"🔍 Analyzing: {sp1} × {sp2}")

    merged['interaction'] = merged[sp1] * merged[sp2]
    T = merged[[sp1, sp2, 'interaction']].values

    # Causal model
    model = LinearDML(
        model_y=RandomForestRegressor(n_estimators=100, random_state=42),
        model_t=RandomForestRegressor(n_estimators=100, random_state=42),
        discrete_treatment=False,
        random_state=42
    )
    model.fit(Y, T, X=X)

    # Extract effects
    try:
        effects = model.const_marginal_effect(X)
        conf_int = model.const_marginal_effect_interval(X)

        if effects.ndim == 1:
            interaction_effect = effects[2]
            lower_ci = conf_int[0][2]
            upper_ci = conf_int[1][2]
        else:
            interaction_effect = effects[:, 2]
            lower_ci = conf_int[0][:, 2].mean()
            upper_ci = conf_int[1][:, 2].mean()

        mean_effect = np.mean(interaction_effect)

        interaction_results.append({
            'Species_1': sp1,
            'Species_2': sp2,
            'Interaction_Effect': mean_effect,
            'CI Lower': lower_ci,
            'CI Upper': upper_ci
        })

    except Exception as e:
        print(f"⚠️ Failed on {sp1} × {sp2}: {e}")
        continue

# === Save results ===
result_df = pd.DataFrame(interaction_results)
