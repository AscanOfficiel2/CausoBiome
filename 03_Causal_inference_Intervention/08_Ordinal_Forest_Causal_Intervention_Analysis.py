import pandas as pd
import numpy as np
from econml.dml import LinearDML
from sklearn.ensemble import RandomForestRegressor
from scipy.stats import ttest_ind
import matplotlib.pyplot as plt
import seaborn as sns

# Load data
expr = pd.read_csv("Expression_Matrix_Aligned.csv")
meta = pd.read_csv("Aligned_metadata.csv")
top_species = pd.read_csv("Top_Important_Species.csv")

species_list = top_species.iloc[:, 0].tolist()
expr_filtered = expr[['Sample_ID'] + species_list]
merged = pd.merge(meta, expr_filtered, on="Sample_ID", how="inner")

# Outcome and covariates
merged['OrdinalOutcome'] = merged['Group'].map({'Healthy': 0, 'Adenoma': 1, 'Cancer': 2})
merged['Sex'] = merged['Sex'].map({'female': 0, 'male': 1})

Y = merged['OrdinalOutcome'].values
X = merged[['Age', 'BMI', 'Sex']].values

# Calculate baseline CRC score
baseline_crc = merged['OrdinalOutcome'].mean()

# Store final intervention results with risk metrics
intervention_results = []
intervention_effects = []

for species in species_list:
    print(f"Analyzing intervention for: {species}")

    T = merged[[species]].values

    # Train model
    dml = LinearDML(
        model_y=RandomForestRegressor(n_estimators=100, random_state=42),
        model_t=RandomForestRegressor(n_estimators=100, random_state=42),
        discrete_treatment=False,
        random_state=42
    )
    dml.fit(Y, T, X=X)

    # ATE
    ate = np.mean(dml.effect(X))

    # Interventions
    std_dev = merged[species].std()
    effect_up = dml.const_marginal_effect(X) * std_dev
    effect_down = dml.const_marginal_effect(X) * -std_dev

    mean_up = np.mean(effect_up)
    mean_down = np.mean(effect_down)

    # Simulated new CRC scores
    simulated_up = baseline_crc + mean_up
    simulated_down = baseline_crc + mean_down

    # Risk metrics
    arr_up = baseline_crc - simulated_up
    rr_up = simulated_up / baseline_crc if baseline_crc != 0 else np.nan
    try:
        or_up = (simulated_up / (1 - simulated_up)) / (baseline_crc / (1 - baseline_crc))
    except ZeroDivisionError:
        or_up = np.nan

    arr_down = baseline_crc - simulated_down
    rr_down = simulated_down / baseline_crc if baseline_crc != 0 else np.nan
    try:
        or_down = (simulated_down / (1 - simulated_down)) / (baseline_crc / (1 - baseline_crc))
    except ZeroDivisionError:
        or_down = np.nan

    # P-value: t-test of local effects
    p_value = ttest_ind(effect_up.flatten(), effect_down.flatten(), equal_var=False).pvalue

    # Store summary metrics
    intervention_results.append({
        'Species': species,
        'ATE': round(ate, 3),
        'Baseline_CRC': round(baseline_crc, 3),
        'Sim_CRC_+1SD': round(simulated_up, 3),
        'ARR_+1SD': round(arr_up, 3),
        'RR_+1SD': round(rr_up, 3),
        'OR_+1SD': round(or_up, 3) if not np.isnan(or_up) else 'NA',
        'Sim_CRC_-1SD': round(simulated_down, 3),
        'ARR_-1SD': round(arr_down, 3),
        'RR_-1SD': round(rr_down, 3),
        'OR_-1SD': round(or_down, 3) if not np.isnan(or_down) else 'NA',
        'P_value': round(p_value, 4)
    })

    # Store raw intervention effects
    intervention_effects.append({
        'Species': species,
        'ATE': ate,
        'Intervention (+1 SD)': mean_up,
        'Intervention (-1 SD)': mean_down
    })

# Save results
output_df = pd.DataFrame(intervention_results)
output_df.to_csv("EconML_Intervention_Effect_Table_With_RiskMetrics.csv", index=False)

intervention_df = pd.DataFrame(intervention_effects)
intervention_df.to_csv("EconML_Intervention_Results.csv", index=False)

print("✅ All results saved successfully.")

