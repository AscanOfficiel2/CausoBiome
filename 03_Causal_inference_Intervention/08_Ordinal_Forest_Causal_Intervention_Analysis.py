"""Random forest Log Loss on Consistent Random forest Features

"""

import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.preprocessing import LabelEncoder
from sklearn.metrics import log_loss

# Load your data
expr_df = pd.read_csv("/content/Expression_Matrix_Aligned.csv", index_col=0)
meta_df = pd.read_csv("/content/Aligned_metadata.csv")
rf_species_df = pd.read_csv("/content/Consistent_Species_Sorted.csv")

# Align sample IDs
meta_df["Sample_ID"] = meta_df["Sample_ID"].astype(str).str.strip()
expr_df.index = expr_df.index.astype(str).str.strip()
meta_df = meta_df.set_index("Sample_ID").loc[expr_df.index]

# Encode group labels
le = LabelEncoder()
meta_df["Group_Code"] = le.fit_transform(meta_df["Group"])
class_names = le.classes_

# Initialize results
results = []

# Loop through each species
for species in rf_species_df["Species"]:
    if species not in expr_df.columns:
        continue

    meta_df["Species_Abundance"] = expr_df[species]

    # Prevalence/variance check
    if meta_df["Species_Abundance"].std() == 0:
        continue

    try:
        X = meta_df[["Species_Abundance"]]
        y = meta_df["Group_Code"]

        model = RandomForestClassifier(n_estimators=100, class_weight='balanced', random_state=42)
        model.fit(X, y)

        # Predict probabilities and compute log-loss
        preds = model.predict_proba(X)
        loss = log_loss(y, preds)

        result_row = {
            "Species": species,
            "Log_Loss": round(loss, 4)
        }

        results.append(result_row)

    except Exception as e:
        print(f"⚠️ Skipping {species} due to error: {e}")
        continue

# Save results
if results:
    df_results = pd.DataFrame(results).sort_values("Log_Loss")
    df_results.to_csv("RF_Log_Loss_Per_Species.csv", index=False)
    print("✅ Random Forest log-loss results saved to 'RF_Log_Loss_Per_Species.csv'")
    df_results.head()
else:
    print("⚠️ No valid species were processed. Check for low variance or missing data.")

