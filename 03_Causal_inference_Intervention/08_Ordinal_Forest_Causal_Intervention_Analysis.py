import pandas as pd
import numpy as np

# Load the intervention table
df = pd.read_csv("EconML_Intervention_Effect_Table_With_RiskMetrics.csv")

# Replace 'NA' strings in OR columns with np.nan for safety
df['OR_+1SD'] = pd.to_numeric(df['OR_+1SD'], errors='coerce')
df['OR_-1SD'] = pd.to_numeric(df['OR_-1SD'], errors='coerce')

# Clip p-values to avoid division by zero or inflated scores
df['P_value_clipped'] = df['P_value'].clip(lower=1e-6)

# Compute unnormalized intervention score
df['InterventionScore'] = (
    df['ARR_+1SD'].abs() +
    df['ARR_-1SD'].abs() +
    df['ATE'].abs()
) * (1 / df['P_value_clipped'])

# Normalize the score to [0–1] using min-max scaling
min_score = df['InterventionScore'].min()
max_score = df['InterventionScore'].max()
df['InterventionScore_Normalized'] = (df['InterventionScore'] - min_score) / (max_score - min_score)

# Sort by normalized score for readability
df_sorted = df.sort_values(by='InterventionScore_Normalized', ascending=False)

# Save final scored and normalized table
df_sorted.to_csv("EconML_Intervention_Score_Normalized.csv", index=False)

