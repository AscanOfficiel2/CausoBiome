from scipy.stats import kruskal
from statsmodels.stats.multitest import multipletests
import os
import math

# Use all 12 species from model input
all_species = list(X.columns)

# Create output directory for plots
os.makedirs("feature_plots", exist_ok=True)

kruskal_results = []

# Perform Kruskal-Wallis test for each species
for species in all_species:
    groups = [merged[merged['Group'] == g][species].dropna() for g in ['Healthy', 'Adenoma', 'Cancer']]
    stat, p_value = kruskal(*groups)
    kruskal_results.append({'Species': species, 'Kruskal_Statistic': stat, 'P_Value': p_value})

# Convert to DataFrame
kruskal_df = pd.DataFrame(kruskal_results)

# Apply FDR correction (Benjamini-Hochberg)
kruskal_df['FDR_Adjusted_P'] = multipletests(kruskal_df['P_Value'], method='fdr_bh')[1]

# Save test results
kruskal_df.to_csv("kruskal_test_results.csv", index=False)

# Filter to significant species (FDR < 0.05)
significant_species = kruskal_df[kruskal_df['FDR_Adjusted_P'] < 0.05]['Species'].tolist()

