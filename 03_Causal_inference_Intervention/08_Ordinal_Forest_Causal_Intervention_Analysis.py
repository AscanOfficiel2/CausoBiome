# -----------------------
# Calculate E-values
# -----------------------
for idx, row in results_df.iterrows():
    ate = row['ATE']
    ci_lower = row['CI Lower']
    ci_upper = row['CI Upper']

    evalue_point, evalue_ci = compute_evalue(ate, ci_lower, ci_upper)

    evalue_results.append({
        'Species': row['Species'],
        'ATE': ate,
        'E-value (Point Estimate)': evalue_point,
        'E-value (Confidence Interval)': evalue_ci
    })

