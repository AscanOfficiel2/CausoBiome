from statsmodels.stats.multitest import multipletests

# -------------------------------
# Step 1: Load long format data
# -------------------------------
df = pd.read_csv("Significant_Species_Abundance_LongFormat.csv")

# -------------------------------
# Step 2: Initialize p-values
# -------------------------------
pvals = []

species_list = df['Species'].unique()

for species in species_list:
    sub_df = df[df['Species'] == species]

    healthy = sub_df[sub_df['Group'] == 'Healthy']['log2_Abundance']
    adenoma = sub_df[sub_df['Group'] == 'Adenoma']['log2_Abundance']
    cancer = sub_df[sub_df['Group'] == 'Cancer']['log2_Abundance']

    # Pairwise Mann–Whitney U tests
    p1 = mannwhitneyu(cancer, healthy, alternative='two-sided').pvalue
    p2 = mannwhitneyu(adenoma, healthy, alternative='two-sided').pvalue
    p3 = mannwhitneyu(cancer, adenoma, alternative='two-sided').pvalue

    pvals.append({
        'Species': species,
        'p_Cancer_vs_Healthy': p1,
        'p_Adenoma_vs_Healthy': p2,
        'p_Cancer_vs_Adenoma': p3
    })

pval_df = pd.DataFrame(pvals)

# -------------------------------
# Step 3: Apply FDR correction
# -------------------------------
for col in ['p_Cancer_vs_Healthy', 'p_Adenoma_vs_Healthy', 'p_Cancer_vs_Adenoma']:
    corrected = multipletests(pval_df[col], method='fdr_bh')[1]
    pval_df[f'FDR_{col}'] = corrected

# -------------------------------
# Step 4: Merge with fold change table
# -------------------------------
fc_df = pd.read_csv("Groupwise_Abundance_and_FoldChange.csv")
fc_df.reset_index(inplace=True)

# Merge both dataframes
final_df = pd.merge(fc_df, pval_df, on='Species')

# Save result
final_df.to_csv("Groupwise_Abundance_FoldChange_with_FDR.csv", index=False)

print("✅ Fold change + statistical tests (with FDR correction) saved to 'Groupwise_Abundance_FoldChange_with_FDR.csv'")

