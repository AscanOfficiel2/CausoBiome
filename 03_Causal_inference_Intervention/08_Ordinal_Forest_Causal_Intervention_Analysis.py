import pandas as pd
import numpy as np

# Function to calculate E-value
# E-value formula from VanderWeele & Ding (2017)
def compute_evalue(estimate, lower_ci, upper_ci):
    rr = np.exp(np.abs(estimate))
    rr_ci = np.exp(np.abs(lower_ci if estimate > 0 else upper_ci))
    evalue_point = rr + np.sqrt(rr * (rr - 1))
    evalue_ci = rr_ci + np.sqrt(rr_ci * (rr_ci - 1))
    return evalue_point, evalue_ci

# -----------------------
# Load data
# -----------------------
results_df = pd.read_csv("DML_Causal_Effects_Per_Species.csv")

# Results container
