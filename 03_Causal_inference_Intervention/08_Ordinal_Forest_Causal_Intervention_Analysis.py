# Microbial Interaction Analysis (Synergistic/Antagonistic)
# using Double Machine Learning (LinearDML)
# ==============================================

import pandas as pd
import numpy as np
from econml.dml import LinearDML
from sklearn.ensemble import RandomForestRegressor
from itertools import combinations

# Load Data
expr = pd.read_csv("Expression_Matrix_Aligned.csv")
meta = pd.read_csv("Aligned_metadata.csv")
top_species = pd.read_csv("Top_Important_Species.csv")

species_list = top_species.iloc[:, 0].tolist()
expr_filtered = expr[['Sample_ID'] + species_list]
merged = pd.merge(meta, expr_filtered, on="Sample_ID", how="inner")

# Define Outcome and Covariates
merged['OrdinalOutcome'] = merged['Group'].map({'Healthy': 0, 'Adenoma': 1, 'Cancer': 2})
merged['Sex'] = merged['Sex'].map({'female': 0, 'male': 1})

Y = merged['OrdinalOutcome'].values
X = merged[['Age', 'BMI', 'Sex']].values

interaction_results = []

for species_pair in combinations(species_list, 2):
    sp1, sp2 = species_pair
    print(f"Analyzing interaction between {sp1} and {sp2}")

    merged['interaction'] = merged[sp1] * merged[sp2]
    T = merged[[sp1, sp2, 'interaction']].values

    dml_model = LinearDML(
        model_y=RandomForestRegressor(n_estimators=100, random_state=42),
        model_t=RandomForestRegressor(n_estimators=100, random_state=42),
        discrete_treatment=False,
        random_state=42
    )

    dml_model.fit(Y, T, X=X)

    # Robust fix: explicitly use const_marginal_effect
    effects = dml_model.const_marginal_effect(X)

    # Check dimensions explicitly
    if effects.ndim == 1 and effects.shape[0] == 3:
        interaction_effect = effects[2]
    else:
        interaction_effect = effects[:, 2]

    mean_interaction_effect = np.mean(interaction_effect)

    # Confidence intervals
    conf_int = dml_model.const_marginal_effect_interval(X)

    if conf_int[0].ndim == 1 and conf_int[0].shape[0] == 3:
        interaction_CI_lower = conf_int[0][2]
        interaction_CI_upper = conf_int[1][2]
    else:
        interaction_CI_lower = np.mean(conf_int[0][:, 2])
        interaction_CI_upper = np.mean(conf_int[1][:, 2])

    interaction_results.append({
        'Species_1': sp1,
        'Species_2': sp2,
        'Interaction_Effect': mean_interaction_effect,
        'CI Lower': interaction_CI_lower,
        'CI Upper': interaction_CI_upper
    })

interaction_df = pd.DataFrame(interaction_results)
interaction_df.to_csv("Microbial_Interaction_Effects_Corrected.csv", index=False)

print("\n✅ Interaction analysis saved to 'Microbial_Interaction_Effects_Corrected.csv'")
print(interaction_df.head())

