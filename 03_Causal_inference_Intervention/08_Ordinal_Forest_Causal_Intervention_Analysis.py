# ===============================
# Ordinal Forest-Style Classifier for Microbiome Data
# ===============================

import pandas as pd
import numpy as np
from sklearn.ensemble import RandomForestClassifier
from sklearn.model_selection import train_test_split, StratifiedKFold, cross_val_score
from sklearn.preprocessing import OrdinalEncoder
from sklearn.metrics import classification_report, confusion_matrix, f1_score, make_scorer
import matplotlib.pyplot as plt
import seaborn as sns

# -------------------------------
# Step 1: Load Data
# -------------------------------
logloss = pd.read_csv("RF_Log_Loss_Per_Species.csv")
expr = pd.read_csv("Expression_Matrix_Aligned.csv")
meta = pd.read_csv("Aligned_metadata.csv")

# -------------------------------
# Step 2: Filter Species by Log Loss (≤ 0.1)
# -------------------------------
filtered_logloss = logloss[logloss["Log_Loss"] <= 0.1]
shortlisted_species_set = set(filtered_logloss["Species"].dropna().astype(str).str.strip())
expr_columns_set = set(expr.columns.astype(str).str.strip())

# -------------------------------
# Step 3: Identify Valid Species Present in Expression Matrix
# -------------------------------
valid_species = sorted(expr_columns_set.intersection(shortlisted_species_set))

print(f"📉 Species with log loss ≤ 0.1: {len(shortlisted_species_set)}")
print(f"✅ Found {len(valid_species)} valid shortlisted species.")

if len(valid_species) == 0:
    raise ValueError("No valid shortlisted species found in expression matrix columns.")

# -------------------------------
# Step 4: Subset Expression Matrix
# -------------------------------
expr_filtered = expr[["Sample_ID"] + valid_species]

# -------------------------------
# Step 5: Merge with Metadata
# -------------------------------
merged = pd.merge(meta, expr_filtered, on="Sample_ID", how="inner")
merged['Group'] = pd.Categorical(merged['Group'], categories=['Healthy', 'Adenoma', 'Cancer'], ordered=True)

# -------------------------------
# Step 6: Drop Missing Data
# -------------------------------
merged = merged.dropna(subset=valid_species + ['Group'])

if merged.empty:
    raise ValueError("No rows remaining after dropping missing values.")

# -------------------------------
# Step 7: Prepare Features and Target
# -------------------------------
X = merged[valid_species].apply(pd.to_numeric, errors='coerce')
y = merged[['Group']]

# Drop columns with too many missing values
na_fraction = X.isna().mean()
X = X.loc[:, na_fraction <= 0.5]

# Impute remaining NAs with median
X = X.fillna(X.median())

# Remove constant columns
X = X.loc[:, X.nunique() > 1]

if X.empty:
    raise ValueError("All features were removed due to missing or constant values.")

# Store the final feature names BEFORE any potential conversion to numpy
feature_names = X.columns.tolist()

# -------------------------------
# Step 8: Encode Group as Ordinal
# -------------------------------
encoder = OrdinalEncoder(categories=[['Healthy', 'Adenoma', 'Cancer']])
y_encoded = encoder.fit_transform(y).ravel().astype(int)

# -------------------------------
# Step 9: Train/Test Split
# -------------------------------
X_train, X_test, y_train, y_test = train_test_split(
    X, y_encoded, test_size=0.33, random_state=42, stratify=y_encoded)

# -------------------------------
# Step 10: Train Random Forest Classifier
# -------------------------------
rf = RandomForestClassifier(
    n_estimators=100,
    class_weight='balanced',
    random_state=42,
    n_jobs=-1
)
rf.fit(X_train, y_train)

# -------------------------------
# Step 10a: Cross-Validation Evaluation
# -------------------------------
cv = StratifiedKFold(n_splits=10, shuffle=True, random_state=42)
# Use the original DataFrame X for cross-validation if needed, or ensure X_train columns match
# If X_train/X_test are numpy arrays, cross_val_score should handle it as long as shapes are consistent
accuracy_scores = cross_val_score(rf, X, y_encoded, cv=cv, scoring='accuracy')
f1_macro_scores = cross_val_score(rf, X, y_encoded, cv=cv, scoring=make_scorer(f1_score, average='macro'))

print("\n🔁 Cross-Validation Results (10-fold):")
print(f"  - Accuracy: {accuracy_scores.mean():.4f} ± {accuracy_scores.std():.4f}")
print(f"  - F1 Macro: {f1_macro_scores.mean():.4f} ± {f1_macro_scores.std():.4f}")

# -------------------------------
# Step 10b: Negative Control - Label Shuffling
# -------------------------------
from sklearn.utils import shuffle
y_shuffled = shuffle(y_encoded, random_state=42)
shuffled_scores = cross_val_score(rf, X, y_shuffled, cv=cv, scoring='accuracy')
print(f"\n🔀 Shuffled Label Accuracy (control): {shuffled_scores.mean():.4f}")

# -------------------------------
# Step 11: Predict and Evaluate on Test Set
# -------------------------------
y_pred = rf.predict(X_test)

print("\n📊 Classification Report:")
# Use the original encoder categories for target names
print(classification_report(y_test, y_pred, target_names=encoder.categories_[0]))

print("\n📊 Confusion Matrix:")
conf_matrix = confusion_matrix(y_test, y_pred)
# Use the original encoder categories for index and columns
conf_df = pd.DataFrame(conf_matrix, index=encoder.categories_[0], columns=encoder.categories_[0])
print(conf_df)

###########################################################################
# -------------------------------
# Step 11a: Compute Multiclass AUROC
# -------------------------------
from sklearn.metrics import roc_auc_score, roc_curve
from sklearn.preprocessing import label_binarize

# Binarize true labels
y_test_bin = label_binarize(y_test, classes=[0, 1, 2])
# Get predicted probabilities
y_proba = rf.predict_proba(X_test)

# Compute AUROC for each class
auroc_per_class = roc_auc_score(y_test_bin, y_proba, average=None)
auroc_macro = roc_auc_score(y_test_bin, y_proba, average='macro')

# Display results
for idx, class_name in enumerate(encoder.categories_[0]):
    print(f"🟢 AUROC - {class_name}: {auroc_per_class[idx]:.4f}")
print(f"⭐ Macro-average AUROC: {auroc_macro:.4f}")

from sklearn.metrics import classification_report

# Re-generate classification report as dict
report_dict = classification_report(y_test, y_pred, target_names=encoder.categories_[0], output_dict=True)

# Prepare summary dictionary
summary_metrics = {
    "Metric": [],
    "Value": []
}

# Add AUROC
for idx, class_name in enumerate(encoder.categories_[0]):
    summary_metrics["Metric"].append(f"AUROC - {class_name}")
    summary_metrics["Value"].append(auroc_per_class[idx])

summary_metrics["Metric"].append("AUROC - Macro Average")
summary_metrics["Value"].append(auroc_macro)

# Add accuracy and F1 scores
summary_metrics["Metric"].append("Cross-Validation Accuracy")
summary_metrics["Value"].append(f"{accuracy_scores.mean():.4f} ± {accuracy_scores.std():.4f}")

summary_metrics["Metric"].append("Cross-Validation F1 Macro")
summary_metrics["Value"].append(f"{f1_macro_scores.mean():.4f} ± {f1_macro_scores.std():.4f}")

summary_metrics["Metric"].append("Shuffled Label Accuracy (control)")
summary_metrics["Value"].append(f"{shuffled_scores.mean():.4f}")

# Add classification report metrics (macro avg, weighted avg, etc.)
for key in report_dict:
    if isinstance(report_dict[key], dict):
        for subkey in report_dict[key]:
            summary_metrics["Metric"].append(f"{key} - {subkey}")
            summary_metrics["Value"].append(report_dict[key][subkey])

# Save to CSV
summary_df = pd.DataFrame(summary_metrics)
summary_df.to_csv("Ordinal_RF_Full_Evaluation_Metrics.csv", index=False)

