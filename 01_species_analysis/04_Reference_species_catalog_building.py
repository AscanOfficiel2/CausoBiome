import pandas as pd
import numpy as np
import re

# Load your data
df = pd.read_excel("/content/CRC_all_Species.xls")

print("Raw data shape:", df.shape)
print("Columns:", df.columns.tolist())

# ============================================
# STEP 2: Filter species-level entries
# ============================================
# Keep only species-level taxa (taxonomy_lvl == "S")
df = df[df["taxonomy_lvl"] == "S"].copy()

# Keep relevant columns only
df = df[["Sample_ID", "Taxonomy_name", "fraction_total_reads"]]

# ============================================
# STEP 3: Pivot to wide format
# ============================================
# Each row = species, each column = sample
wide = df.pivot_table(index="Taxonomy_name", columns="Sample_ID",
                      values="fraction_total_reads", aggfunc="sum", fill_value=0)

print(f"✅ Pivoted matrix shape: {wide.shape}")

# ============================================
# STEP 3b: Remove non-microbial taxa (e.g. Homo sapiens)
# ============================================

# Define non-microbial keywords (customizable)
non_microbes = [
    "Homo sapiens", "Homo_sapiens", "Mus musculus", "Rattus",
    "Bos taurus", "Arabidopsis", "Zea mays", "Oryza",
    "Drosophila", "Danio rerio", "Unclassified", "uncultured", "unknown"
]

pattern = re.compile("|".join(non_microbes), flags=re.IGNORECASE)

# Filter out non-microbial species
before = wide.shape[0]
wide = wide[~wide.index.str.contains(pattern)]
after = wide.shape[0]

print(f"✅ Removed {before - after} non-microbial taxa (kept {after} microbial species)")

# ============================================
# STEP 4: Normalize (each sample sums to 1)
# ============================================
wide = wide.div(wide.sum(axis=0), axis=1)
print("✅ Normalized each sample to relative abundance")

# ============================================
# STEP 5: Filter out low-prevalence species
# ============================================
presence = (wide > 0).sum(axis=1) / wide.shape[1]
filtered = wide.loc[presence >= 0.05].copy()

print(f"✅ Retained {filtered.shape[0]} species (present in ≥5% of samples)")
print(f"Filtered out {wide.shape[0] - filtered.shape[0]} low-prevalence taxa")

# ============================================
# STEP 6: Save outputs for R
# ============================================
filtered.to_csv("CRC_species_matrix_filtered.csv")
wide.to_csv("CRC_species_matrix_unfiltered.csv")

print("\n✅ Files saved:")
print(" - CRC_species_matrix_filtered.csv  (microbial-only, normalized, ≥5% prevalence)")
print(" - CRC_species_matrix_unfiltered.csv (microbial-only, normalized, all taxa)")

# Optional Excel versions for inspection
filtered.to_excel("CRC_species_matrix_filtered.xlsx")
wide.to_excel("CRC_species_matrix_unfiltered.xlsx")

print("🎯 Done — microbial-only species matrices ready for R (CLR, diversity, prevalence).")

