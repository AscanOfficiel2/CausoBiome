import pandas as pd, re
from pathlib import Path

# Helper: clean species names for cross-dataset harmonization
def clean_species_name(name: str) -> str:
    if pd.isna(name):
        return None
    s = re.sub(r"\[[^\]]+\]", "", str(name))
    s = re.sub(r"\([^)]*\)", "", s)
    s = s.split("|")[0]
    s = s.replace("_", " ").strip().lower()
    s = re.sub(r"\s{2,}", " ", s)
    return s


# ============================================
# STEP 2: Load Excel files
# ============================================
wirbel = pd.read_excel("wirbel_list.xlsx")
piccino = pd.read_excel("Piccino_study_list.xlsx")

# ============================================
# STEP 3: Extract Wirbel markers (core & extended)
# ============================================
for c in ["p.adj.meta", "fc.meta", "auc.meta"]:
    if c in wirbel.columns:
        wirbel[c] = pd.to_numeric(wirbel[c], errors="coerce")

wirbel["clean_species"] = wirbel["species"].apply(clean_species_name)

# Core thresholds (stringent)
core_mask = (wirbel["p.adj.meta"] <= 0.05) & (wirbel["fc.meta"].abs() >= 0.5)
wirbel_core = wirbel.loc[core_mask].copy()

# Extended thresholds (relaxed)
ext_mask = (wirbel["p.adj.meta"] <= 0.10) & (wirbel["fc.meta"].abs() >= 0.3)
wirbel_ext = wirbel.loc[ext_mask].copy()

# Direction annotation
wirbel_core["direction"] = wirbel_core["fc.meta"].apply(lambda x: "enriched_in_CRC" if x > 0 else "depleted_in_CRC")
wirbel_ext["direction"]  = wirbel_ext["fc.meta"].apply(lambda x: "enriched_in_CRC" if x > 0 else "depleted_in_CRC")

# Columns to keep
cols = ["species","clean_species","p.adj.meta","fc.meta","auc.meta","direction"]
wirbel_core[cols].to_csv("wirbel_markers_core.csv", index=False)
wirbel_ext[cols].to_csv("wirbel_markers_extended.csv", index=False)

print(f"✅ Wirbel markers: {len(wirbel_core)} core, {len(wirbel_ext)} extended")


# ============================================
# STEP 4: Extract Piccino stage-associated species
# ============================================
piccino["clean_species"] = piccino["feature"].apply(clean_species_name)
mask = (piccino["metadata"].astype(str).str.lower() == "stage_class") & (piccino["qval"] <= 0.1)
pic_stage = piccino.loc[mask].copy()

agg = (pic_stage.groupby("clean_species")
       .agg(n_sig=("qval","size"), min_q=("qval","min"), mean_coef=("coef","mean"))
       .reset_index()
       .sort_values(["n_sig","min_q"], ascending=[False,True]))

agg.to_csv("piccino_stage_associated_species.csv", index=False)
print(f"✅ Piccino stage-associated species: {len(agg)}")

# ============================================
# STEP 5: Merge into unified CRC reference panel
# ============================================
# Core markers from Wirbel (high confidence)
wir_core = wirbel_core[["clean_species","direction","p.adj.meta","fc.meta","auc.meta"]].copy()
wir_core["source"] = "Wirbel_core"

# Extended markers
wir_ext = wirbel_ext[["clean_species","direction","p.adj.meta","fc.meta","auc.meta"]].copy()
wir_ext["source"] = "Wirbel_extended"

# Piccino stage-associated
pic_df = agg[["clean_species","n_sig","min_q","mean_coef"]].copy()
pic_df["direction"] = pic_df["mean_coef"].apply(lambda x: "enriched_in_CRC_stage" if x > 0 else "depleted_in_CRC_stage")
pic_df["source"] = "Piccino_stage"

# Merge all
merged = pd.concat([wir_core, wir_ext, pic_df], ignore_index=True)
merged = merged.drop_duplicates(subset=["clean_species","source"]).reset_index(drop=True)
merged.to_csv("CRC_reference_marker_panel.csv", index=False)

