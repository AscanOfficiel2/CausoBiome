import pandas as pd
import numpy as np
import networkx as nx
import matplotlib.pyplot as plt
import matplotlib.cm as cm
import matplotlib.colors as mcolors
from matplotlib.lines import Line2D

# === LOAD DATA ===
abundance = pd.read_csv("hellinger_subset_combat_afterbatch_matrix.csv", index_col=0).T
trend_df = pd.read_csv("crc_trend_clustered_biomarkers.csv")  # includes 'Species'

# === FILTER TO POST-HOC SPECIES ===
species_list = trend_df["Species"].unique()
abundance_filtered = abundance[abundance.columns.intersection(species_list)]

# === COMPUTE SPEARMAN CORRELATION ===
corr = abundance_filtered.corr(method="spearman")

# === BUILD EDGE LIST (exclude self-correlation) ===
edges_signed = [(i, j, corr.loc[i, j]) for i in corr.columns for j in corr.index if i != j]

# === BUILD GRAPH ===
G = nx.Graph()
for src, tgt, weight in edges_signed:
    G.add_edge(src, tgt, weight=weight)

# Add isolated nodes
for sp in species_list:
    if sp not in G:
        G.add_node(sp)

# === ABS GRAPH FOR LAYOUT ===
G_abs = nx.Graph()
for src, tgt, weight in edges_signed:
    G_abs.add_edge(src, tgt, weight=abs(weight))
for sp in species_list:
    if sp not in G_abs:
        G_abs.add_node(sp)

# === LAYOUT ===
pos = nx.kamada_kawai_layout(G_abs)

# === EDGE STYLES ===
edge_colors = ['#1f77b4' if G[u][v]['weight'] > 0 else '#d62728' for u, v in G.edges()]
edge_widths = [np.clip(abs(G[u][v]['weight']), 0.1, 1.0) * 1.5 for u, v in G.edges()]

# === NODE STYLE BY DEGREE CENTRALITY ===
centrality = nx.degree_centrality(G)
node_sizes = [np.clip(centrality[n] * 2000, 100, 1500) for n in G.nodes()]

# Use a bright colormap and lighten with alpha
centrality_vals = np.array(list(centrality.values()))
norm = mcolors.Normalize(vmin=centrality_vals.min(), vmax=centrality_vals.max())
cmap = cm.get_cmap('cool')  # brighter and softer
node_color = [cmap(norm(centrality[n])) for n in G.nodes()]

# === PLOT NETWORK ===
plt.figure(figsize=(11, 8))
nx.draw_networkx_nodes(G, pos,
    node_size=node_sizes,
    node_color=node_color,
    edgecolors='black',
    linewidths=1.0,
    alpha=0.85
)
nx.draw_networkx_edges(G, pos,
    edge_color=edge_colors,
    width=edge_widths,
    alpha=0.5,
    connectionstyle="arc3,rad=0.2"
)
nx.draw_networkx_labels(G, pos, font_size=8, font_weight='bold')

# === LEGEND ===
legend_elements = [
    Line2D([0], [0], color='#1f77b4', lw=2, label='Positive correlation'),
    Line2D([0], [0], color='#d62728', lw=2, label='Negative correlation')
]
plt.legend(handles=legend_elements, loc='lower right', bbox_to_anchor=(1.02, 1),
           title="Edge Correlation", fontsize=8, title_fontsize=8, frameon=False)

plt.axis('off')
plt.tight_layout()
plt.savefig("cooccurrence_network_curved_edges.png", dpi=600, bbox_inches="tight")
plt.show()

# === EXPORT CORRELATION VALUES ===
corr_long = corr.stack().reset_index()
corr_long.columns = ["Species1", "Species2", "SpearmanR"]
corr_long = corr_long[corr_long["Species1"] != corr_long["Species2"]]
corr_long.to_csv("correlation_values.csv", index=False)

# === EXPORT NETWORK METRICS ===
metrics_df = pd.DataFrame({
    "Species": list(G.nodes),
    "Degree": [G.degree(n) for n in G.nodes()],
    "DegreeCentrality": [centrality[n] for n in G.nodes()],
    "Closeness": [nx.closeness_centrality(G)[n] for n in G.nodes()],
    "Betweenness": [nx.betweenness_centrality(G)[n] for n in G.nodes()],
})
metrics_df.to_csv("network_metrics.csv", index=False)
