# ===  Load files ===
# Replace these with your actual file paths
dunn_path = "dunn_posthoc_results.csv"  # Output from Dunn’s test
abundance_path = "hellinger_subset_combat_afterbatch_matrix.csv"
metadata_path = "Aligned_metadata_Taxonomy.csv"

# Load data
dunn_df = pd.read_csv(dunn_path)
abundance_df = pd.read_csv(abundance_path, index_col=0).T  # samples as rows
metadata_df = pd.read_csv(metadata_path)

# ===  Merge abundance and metadata ===
abundance_df.index = abundance_df.index.astype(str)
metadata_df["Sample_ID"] = metadata_df["Sample_ID"].astype(str)
merged_df = abundance_df.merge(metadata_df[["Sample_ID", "Group"]],
                               left_index=True, right_on="Sample_ID")

# === Filter significant comparisons ===
dunn_df = dunn_df[dunn_df["FDR_Adjusted_P"] < 0.05].copy()

# === Compute direction based on median abundance ===
directions = []
for _, row in dunn_df.iterrows():
    species = row["Species"]
    g1, g2 = row["Group1"], row["Group2"]

    median1 = merged_df[merged_df["Group"] == g1][species].median()
    median2 = merged_df[merged_df["Group"] == g2][species].median()

    if median1 > median2:
        directions.append(f"{g1} > {g2}")
    elif median2 > median1:
        directions.append(f"{g2} > {g1}")
    else:
        directions.append("No difference")

dunn_df["Direction"] = directions
dunn_df.rename(columns={"FDR_Adjusted_P": "FDR_P"}, inplace=True)

# === Classify trend category ===
def classify_trend(row):
    d = row["Direction"]
    if "Cancer > Adenoma" in d or "Cancer > Healthy" in d:
        return "Late CRC Enriched"
    elif "Adenoma > Healthy" in d:
        return "Early CRC Enriched"
    elif "Healthy > Adenoma" in d:
        return "Early CRC Depleted"
    elif "Healthy > Cancer" in d:
        return "Late CRC Depleted"
    else:
        return "Ambiguous/Complex"

dunn_df["Trend"] = dunn_df.apply(classify_trend, axis=1)

# === Final summary table ===
summary = dunn_df[["Species", "Group1", "Group2", "Direction", "FDR_P", "Trend"]]
summary.sort_values(["Trend", "Species", "FDR_P"], inplace=True)

# === Save to file
summary.to_csv("crc_trend_clustered_biomarkers.csv", index=False)
print("Clustered biomarker trends saved as crc_trend_clustered_biomarkers.csv")

