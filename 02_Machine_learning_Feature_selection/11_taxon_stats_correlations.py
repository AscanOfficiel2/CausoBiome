# === Load your files ===
# Replace with your actual file paths if not using uploads
abundance = pd.read_csv("hellinger_subset_combat_afterbatch_matrix.csv", index_col=0).T
metadata = pd.read_csv("Aligned_metadata_Taxonomy.csv")
rf_robust = pd.read_csv("robust_biomarkers.20250624csv")
ordinal = pd.read_csv("ordinal_forest_feature_importance.csv").rename(columns={"Gene": "Feature"})

# === Step 1: Filter RF to consistent only ===
rf_consistent = rf_robust[rf_robust["Consistent"] == 1]
rf_species_set = set(rf_consistent["Feature"])
ordinal_species_set = set(ordinal["Feature"])
overlap_species = list(rf_species_set.intersection(ordinal_species_set))

# === Step 2: Subset matrix to overlapping species ===
abundance = abundance[overlap_species]

## Merge RF robustness metadata (e.g. Importance, Stability, Consistency)
rf_full = rf_robust[["Feature", "Importance", "Stability", "Consistent"]].rename(
    columns={
        "Importance": "RF_Importance",
        "Stability": "RF_Stability",
        "Consistent": "RF_Consistent"
    }
)

# Merge Ordinal importance
ordinal_imp = ordinal[["Feature", "Importance"]].rename(columns={"Importance": "Ordinal_Importance"})

# Merge both on overlapping species
overlap_meta = pd.merge(rf_full, ordinal_imp, on="Feature")
overlap_meta = overlap_meta.sort_values("Ordinal_Importance", ascending=False)

# Save to file
overlap_meta.to_csv("Overlap_RF_Ordinal_Metadata.csv", index=False)
print("Overlap with RF and Ordinal importance + metadata saved to Overlap_RF_Ordinal_Metadata.csv")


# === Step 3: Merge metadata with abundance ===
metadata["Sample_ID"] = metadata["Sample_ID"].astype(str)
abundance.index = abundance.index.astype(str)
merged = abundance.merge(metadata[["Sample_ID", "Group"]], 
                         left_index=True, right_on="Sample_ID")

# === Step 4: Run Kruskal-Wallis for each species ===
kruskal_results = []
for species in overlap_species:
    grouped = [group[species].values for name, group in merged.groupby("Group")]
    stat, p = kruskal(*grouped)
    kruskal_results.append({"Species": species, "Kruskal_Stat": stat, "P_Value": p})

kruskal_df = pd.DataFrame(kruskal_results)
kruskal_df["FDR_Adjusted_P"] = multipletests(kruskal_df["P_Value"], method="fdr_bh")[1]
kruskal_df = kruskal_df.sort_values("FDR_Adjusted_P")

# View top results
kruskal_df.head(10)

# === Step 5: Run Dunn’s post-hoc test with FDR ===
dunn_all = []
top_species = kruskal_df.head(20)["Species"]

for species in top_species:
    dunn_raw = sp.posthoc_dunn(
        merged[[species, "Group"]].rename(columns={species: "value", "Group": "group"}),
        val_col="value", group_col="group", p_adjust=None
    )
    # Unstack to long format
    dunn_melted = dunn_raw.where(np.triu(np.ones(dunn_raw.shape), k=1).astype(bool)) \
                          .stack().reset_index()
    dunn_melted.columns = ["Group1", "Group2", "Raw_P"]
    dunn_melted["Species"] = species
    dunn_all.append(dunn_melted)

dunn_df = pd.concat(dunn_all, ignore_index=True)
dunn_df["FDR_Adjusted_P"] = multipletests(dunn_df["Raw_P"], method="fdr_bh")[1]
dunn_df = dunn_df.sort_values("FDR_Adjusted_P")

# Display top significant post-hoc results
dunn_df.head(15)

# === Save Kruskal-Wallis results
kruskal_df.to_csv("kruskal_results.csv", index=False)
print("Saved Kruskal-Wallis results to kruskal_results.csv")

# === Save Dunn's post-hoc results
dunn_df.to_csv("dunn_posthoc_results.csv", index=False)
print(" Saved Dunn's post-hoc results to dunn_posthoc_results.csv")


