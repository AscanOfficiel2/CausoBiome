"""Statistical Evaluation of Synthetic data"""

import pandas as pd
import numpy as np
from scipy.stats import ks_2samp
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import roc_auc_score, silhouette_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.decomposition import PCA
from sklearn.manifold import TSNE
import matplotlib.pyplot as plt
import seaborn as sns

# === LOAD DATA ===
real = pd.read_csv("combined_ARG_VFDB_final_DATA_transposed.csv")
syn = pd.read_csv("/content/PCA_synthetic_hellinger_balanced_PCA.csv")

real["source"] = "Real"
syn["source"] = "Synthetic"

combined = pd.concat([real, syn], ignore_index=True)
combined = combined.dropna(axis=1, how='any')  # drop columns with NA

# === Prepare Features and Labels ===
non_feature_cols = ["Sample_ID", "Group", "source"]
X = combined.drop(columns=[c for c in non_feature_cols if c in combined.columns], errors='ignore')
y = (combined["source"] == "Synthetic").astype(int)

# === 1. KS TEST on Top 100 Variable Features ===
feature_variances = X.var().sort_values(ascending=False)
top_features = feature_variances.head(100).index
ks_results = []

for feature in top_features:
    ks_stat, p_value = ks_2samp(real[feature], syn[feature])
    ks_results.append({"Feature": feature, "KS_stat": ks_stat, "p_value": p_value})

ks_df = pd.DataFrame(ks_results)
ks_df.to_csv("ks_test_top_100_features.csv", index=False)
print("KS test saved to ks_test_top_100_features.csv")


# === 3. Silhouette Score in PCA and t-SNE space ===
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# PCA
pca = PCA(n_components=2)
X_pca = pca.fit_transform(X_scaled)
silhouette_pca = silhouette_score(X_pca, y)
print(f"Silhouette Score (PCA): {silhouette_pca:.3f}")

# t-SNE
tsne = TSNE(n_components=2, perplexity=30, random_state=42)
X_tsne = tsne.fit_transform(X_scaled)
silhouette_tsne = silhouette_score(X_tsne, y)
print(f"Silhouette Score (t-SNE): {silhouette_tsne:.3f}")

# === Optional: Plot PCA/t-SNE ===
combined["PC1"], combined["PC2"] = X_pca[:, 0], X_pca[:, 1]
sns.scatterplot(data=combined, x="PC1", y="PC2", hue="source")
plt.title("PCA: Real vs Synthetic")
plt.savefig("pca_real_vs_synthetic.png", dpi=300)
plt.clf()

combined["TSNE1"], combined["TSNE2"] = X_tsne[:, 0], X_tsne[:, 1]
sns.scatterplot(data=combined, x="TSNE1", y="TSNE2", hue="source")
plt.title("t-SNE: Real vs Synthetic")
plt.savefig("tsne_real_vs_synthetic.png", dpi=300)
plt.clf()

print("PCA and t-SNE plots saved.")
