#!/usr/bin/env python3
import pandas as pd
import numpy as np
import os
from pathlib import Path
from sklearn.decomposition import PCA

# === CONFIGURATION ===
REAL_HELLINGER = "combined_ARG_VFDB_final_DATA.csv"  # genes x samples before transpose
REAL_METADATA = "Metadata_Aligned_VF_ARG_CountMatrix.csv"
OUTPUT_DIR = "synthetic_output_pca_phase2"
BALANCED_N = 1000  # samples per class in balanced version
SEED = 42
EXPLAINED_VAR = 0.95  # keep 95% variance in PCA

np.random.seed(SEED)
os.makedirs(OUTPUT_DIR, exist_ok=True)

# === LOAD DATA ===
print("Loading real data...")
hellinger_df = pd.read_csv(REAL_HELLINGER, index_col=0).T  # samples x genes
metadata_df = pd.read_csv(REAL_METADATA)
sample_col = [c for c in metadata_df.columns if c.lower().startswith("sample")][0]
metadata_df[sample_col] = metadata_df[sample_col].astype(str)
hellinger_df.index = hellinger_df.index.astype(str)

# Match sample IDs
common_ids = sorted(set(hellinger_df.index) & set(metadata_df[sample_col]))
hellinger_df = hellinger_df.loc[common_ids]
metadata_df = metadata_df.set_index(sample_col).loc[common_ids]

gene_cols = hellinger_df.columns
group_labels = metadata_df["Group"].unique()

def generate_pca_synthetic_class(group, n_samples):
    group_data = hellinger_df[metadata_df["Group"] == group]
    if len(group_data) < 5:
        raise ValueError(f"Too few samples for PCA in group '{group}'")

    pca = PCA(n_components=EXPLAINED_VAR, svd_solver='full')
    pca.fit(group_data)

    # Sample from standard normal, then transform
    synthetic_scores = np.random.normal(size=(n_samples, pca.n_components_))
    synthetic_genes = synthetic_scores @ pca.components_ + pca.mean_
    synthetic_genes = np.clip(synthetic_genes, 0, 1)
    df = pd.DataFrame(synthetic_genes, columns=gene_cols)

    # Bootstrap metadata
    group_meta = metadata_df[metadata_df["Group"] == group]
    sampled_meta = group_meta.sample(n=n_samples, replace=True, random_state=SEED).reset_index()
    df.insert(0, "Sample_ID", [f"{group}_synPCA_{i}" for i in range(n_samples)])
    sampled_meta["Sample_ID"] = df["Sample_ID"]

    return df, sampled_meta

# === ORIGINAL RATIO SYNTHETIC SET ===
print("Generating PCA-enhanced synthetic data (real ratio)...")
ratio_hellinger = []
ratio_metadata = []

for group in group_labels:
    n_samples = (metadata_df["Group"] == group).sum()
    syn_X, syn_meta = generate_pca_synthetic_class(group, n_samples)
    ratio_hellinger.append(syn_X)
    ratio_metadata.append(syn_meta)

pd.concat(ratio_hellinger).reset_index(drop=True).to_csv(
    os.path.join(OUTPUT_DIR, "PCA_synthetic_hellinger_real_ratio.csv"), index=False)
pd.concat(ratio_metadata).reset_index(drop=True).to_csv(
    os.path.join(OUTPUT_DIR, "PCA_synthetic_metadata_real_ratio.csv"), index=False)

# === BALANCED SYNTHETIC SET ===
print("Generating PCA-enhanced synthetic data (balanced)...")
balanced_hellinger = []
balanced_metadata = []

for group in group_labels:
    syn_X, syn_meta = generate_pca_synthetic_class(group, BALANCED_N)
    balanced_hellinger.append(syn_X)
    balanced_metadata.append(syn_meta)

pd.concat(balanced_hellinger).reset_index(drop=True).to_csv(
    os.path.join(OUTPUT_DIR, "PCA_synthetic_hellinger_balanced_PCA.csv"), index=False)
pd.concat(balanced_metadata).reset_index(drop=True).to_csv(
    os.path.join(OUTPUT_DIR, "PCA_synthetic_metadata_balanced_PCA.csv"), index=False)

print("PCA-enhanced synthetic data generation completed.")

