cancer_pls3  = merged.loc[merged["Group"] == "Cancer",  "PLS_3"]

# -----------------------------
# 3️⃣ Compute ANOVA effect sizes
# -----------------------------
def cohen_f_from_anova(groups):
    group_means = [np.mean(g) for g in groups]
    grand_mean  = np.mean(np.concatenate(groups))
    ss_between  = sum([len(g) * (m - grand_mean)**2 for g, m in zip(groups, group_means)])
    ss_within   = sum([sum((g - np.mean(g))**2) for g in groups])
    eta_sq      = ss_between / (ss_between + ss_within)
    f           = np.sqrt(eta_sq / (1 - eta_sq))
    return f, eta_sq

