# ------------------------------------------------------------
# 1️⃣ Load datasets
# ------------------------------------------------------------
internal_tpm = pd.read_csv("Combined_CLR.csv", index_col=0)
internal_meta = pd.read_csv("Metadata_Aligned_to_FilteredMatrix.csv")
external_tpm = pd.read_csv("Combined_CLR_ext.csv", index_col=0)
external_meta = pd.read_csv("Metadata_Aligned_to_FilteredMatrix_ext.csv")

# ------------------------------------------------------------
# 2️⃣ Load PLS-DML genes (PLS₁ & PLS₃)
# ------------------------------------------------------------
pls_genes = pd.read_csv("PLS_TopGenes_Ranked_with_ComponentStats.csv")
focus_components = ["PLS_1", "PLS_3"]
marker_genes = pls_genes[pls_genes["Component"].isin(focus_components)]["Gene"].unique().tolist()
print(f"✅ Loaded {len(marker_genes)} PLS-DML genes from components {focus_components}")

# ------------------------------------------------------------
# 3️⃣ Align datasets
# ------------------------------------------------------------
internal_samples = internal_tpm.columns.intersection(internal_meta["Sample_ID"])
external_samples = external_tpm.columns.intersection(external_meta["Sample_ID"])
internal_tpm = internal_tpm[internal_samples]
external_tpm = external_tpm[external_samples]
internal_meta = internal_meta[internal_meta["Sample_ID"].isin(internal_samples)]
external_meta = external_meta[external_meta["Sample_ID"].isin(external_samples)]

common_genes = [g for g in marker_genes if g in internal_tpm.index and g in external_tpm.index]
print(f"✅ {len(common_genes)} overlapping genes between internal & external data")

if len(common_genes) < 5:
    raise ValueError("Too few overlapping genes between internal and external datasets!")

# ------------------------------------------------------------
# 4️⃣ Prepare binary labels (Control vs CRC)
# ------------------------------------------------------------
X_train = internal_tpm.loc[common_genes].T
X_ext   = external_tpm.loc[common_genes].T

# Internal: Healthy → 0, Adenoma/Cancer → 1
internal_meta["BinaryGroup"] = internal_meta["Group"].replace({
    "Healthy": 0, "Adenoma": 1, "Cancer": 1
}).astype(int)

# External: Control → 0, CRC/Case/Cancer → 1
external_meta["BinaryGroup"] = external_meta["Group"].replace({
    "Control": 0, "Healthy": 0, "CRC": 1, "Case": 1, "Cancer": 1
}).astype(int)

y_train = internal_meta["BinaryGroup"]
y_ext   = external_meta["BinaryGroup"]

print(f"✅ Training samples: {X_train.shape[0]} | Validation samples: {X_ext.shape[0]}")
print("Class distribution (internal):")
print(y_train.value_counts().rename({0: "Control", 1: "CRC"}))

# ------------------------------------------------------------
# 5️⃣ Define Logistic Regression model & tuning grid
# ------------------------------------------------------------
pipe = Pipeline([
    ("scaler", StandardScaler()),
    ("logreg", LogisticRegression(max_iter=5000, class_weight="balanced", random_state=42))
])

param_grid = {
    "logreg__penalty": ["l1", "l2"],
    "logreg__C": [0.05, 0.1, 0.5, 1, 2, 5],
    "logreg__solver": ["liblinear", "saga"]
}

# ------------------------------------------------------------
# 6️⃣ Tune with 5-fold stratified CV (internal)
# ------------------------------------------------------------
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
