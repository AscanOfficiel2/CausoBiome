plt.legend(frameon=True, loc="lower right")

# Make borders thick and black
for spine in plt.gca().spines.values():
    spine.set_linewidth(2)
    spine.set_edgecolor("black")

sns.despine()
plt.tight_layout()
plt.savefig("External_ROC_LogisticRegression_Publication.png", dpi=600, bbox_inches="tight")
plt.show()

# ------------------------------------------------------------
# 🔟 Save metrics
# ------------------------------------------------------------
pd.DataFrame([metrics]).to_csv("External_LogReg_Publication_Metrics.csv", index=False)

print("\n✅ Logistic Regression (publication version) complete — results saved to:")
