# ------------------------------------------------------------
# Parameters
# ------------------------------------------------------------
n_repeats = 30          # number of stability repeats
perm_repeats = 3        # repeats within permutation importance
top_k = 60              # top-K features to refine via permutation
save_every = 10         # save progress every N repeats

# Tuned / consistent model hyperparameters
rf_params = {
    "n_estimators": 300,
    "max_depth": 3,
    "min_samples_split": 2,
    "min_samples_leaf": 1,
    "max_features": "log2",
    "class_weight": "balanced",
    "n_jobs": -1
}

gb_params = {
    "n_estimators": 500,
    "learning_rate": 0.1,
    "max_depth": 5,
    "subsample": 0.6
}

# Stratified CV
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=GLOBAL_SEED)

# Containers
rf_perm_imps = []   # permutation importances for RF
gb_importances = [] # built-in importances for GB
perm_stability = [] # top-K permutation for GB

# Ensure directory
os.makedirs("importance_partials", exist_ok=True)

# ------------------------------------------------------------
# Main loop: reproducible repeats × CV folds
# ------------------------------------------------------------
for repeat in range(1, n_repeats + 1):
    local_seed = GLOBAL_SEED + repeat
    print(f"\n🌱 Repeat {repeat}/{n_repeats}")

    for fold, (tr_idx, te_idx) in enumerate(cv.split(X, y), 1):
        t0 = time.time()
        X_tr, X_te = X[tr_idx], X[te_idx]
        y_tr, y_te = y[tr_idx], y[te_idx]

