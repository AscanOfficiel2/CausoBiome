from sklearn.model_selection import train_test_split, StratifiedKFold, GridSearchCV
from sklearn.metrics import (
    accuracy_score, balanced_accuracy_score, f1_score,
    cohen_kappa_score, classification_report, confusion_matrix
)
from sklearn.ensemble import GradientBoostingClassifier, RandomForestClassifier

# =======================
# 1. Load Data
# =======================
tpm = pd.read_csv("Combined_CLR.csv", index_col=0)  # species x samples
meta = pd.read_csv("Metadata_Aligned_to_FilteredMatrix.csv")

# Align sample IDs
common_samples = tpm.columns.intersection(meta["Sample_ID"])
tpm = tpm[common_samples]
meta = meta[meta["Sample_ID"].isin(common_samples)].reset_index(drop=True)
tpm = tpm[meta["Sample_ID"]]   # enforce same order

X = tpm.T.values
y = meta["Group"].values

# =======================
# 2. Train/test split (hold-out 20%)
# =======================
X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=SEED, stratify=y
)

# =======================
# 3. Models + Param Grids
# =======================
models = {
    "RandomForest": RandomForestClassifier(random_state=SEED, class_weight="balanced", n_jobs=-1),
    "GradientBoosting": GradientBoostingClassifier(random_state=SEED)
}

param_grids = {
    "RandomForest": {
        "n_estimators": [100, 300, 500],
        "max_depth": [3, 7, 12],
        "min_samples_split": [2, 5, 10],
        "min_samples_leaf": [1, 2, 4],
        "max_features": ["sqrt", "log2", None]
    },
    "GradientBoosting": {
        "n_estimators": [100, 300, 500],
        "learning_rate": [0.01, 0.05, 0.1],
        "max_depth": [3, 5, 7],
        "subsample": [0.6, 0.8, 1.0]
    }
}

# =======================
# 4. Nested CV setup
# =======================
outer = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
inner = StratifiedKFold(n_splits=3, shuffle=True, random_state=SEED)

cv_summary = []
fold_records = []
best_params = {}

for name, base_model in models.items():
    outer_metrics = defaultdict(list)

    for fold, (tr_idx, te_idx) in enumerate(outer.split(X_train, y_train), 1):
        X_tr, X_te = X_train[tr_idx], X_train[te_idx]
        y_tr, y_te = y_train[tr_idx], y_train[te_idx]

        gs = GridSearchCV(
            base_model, param_grids[name], cv=inner,
            scoring="balanced_accuracy", n_jobs=-1
        )
        gs.fit(X_tr, y_tr)
        best = gs.best_estimator_

        y_pred = best.predict(X_te)
        acc = accuracy_score(y_te, y_pred)
        bacc = balanced_accuracy_score(y_te, y_pred)
        f1 = f1_score(y_te, y_pred, average="macro")
        kappa = cohen_kappa_score(y_te, y_pred)

        outer_metrics["Accuracy"].append(acc)
        outer_metrics["BalancedAcc"].append(bacc)
        outer_metrics["F1_macro"].append(f1)
        outer_metrics["Kappa"].append(kappa)

        fold_records.append({
            "Model": name,
            "Fold": fold,
            "Accuracy": acc,
            "BalancedAcc": bacc,
            "F1_macro": f1,
            "Kappa": kappa
        })

    # Summary across outer folds
    cv_summary.append({
        "Model": name,
        "MeanAcc": np.mean(outer_metrics["Accuracy"]),
        "StdAcc": np.std(outer_metrics["Accuracy"]),
        "MeanBalancedAcc": np.mean(outer_metrics["BalancedAcc"]),
        "StdBalancedAcc": np.std(outer_metrics["BalancedAcc"]),
        "MeanF1": np.mean(outer_metrics["F1_macro"]),
        "MeanKappa": np.mean(outer_metrics["Kappa"])
    })

    # Best params on full training set
    gs_full = GridSearchCV(
        base_model, param_grids[name], cv=inner,
        scoring="balanced_accuracy", n_jobs=-1
    )
    gs_full.fit(X_train, y_train)
    best_params[name] = gs_full.best_params_

# Save nested CV results
cv_df = pd.DataFrame(cv_summary).sort_values("MeanBalancedAcc", ascending=False)
pd.concat([pd.DataFrame(fold_records)]).to_csv("NestedCV_folds_RF_GB.csv", index=False)
cv_df.to_csv("NestedCV_summary_RF_GB.csv", index=False)
pd.DataFrame(best_params).to_csv("NestedCV_best_params_RF_GB.csv")

print("Nested CV summary:\n", cv_df)
print("Selected params:\n", best_params)

# =======================
# 5. Final model on hold-out set
# =======================
winner = cv_df.iloc[0]["Model"]
