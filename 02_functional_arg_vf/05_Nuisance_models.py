# ------------------------------------------------------------
#  Function: train, evaluate, and save metrics
# ------------------------------------------------------------
def evaluate_model(name, model, X_train, y_train, X_test, y_test, filename):
    """Train model, evaluate on test set, and save metrics/reports."""
    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)

    metrics = {
        "Model": name,
        "Accuracy": accuracy_score(y_test, y_pred),
        "BalancedAcc": balanced_accuracy_score(y_test, y_pred),
        "F1_macro": f1_score(y_test, y_pred, average="macro"),
        "Kappa": cohen_kappa_score(y_test, y_pred)
    }

    print(f"\n📊 Hold-out performance ({name}):")
    for k, v in metrics.items():
        if k != "Model":
            print(f"  {k}: {v:.3f}")

    # --- Save overall metrics
    pd.DataFrame([metrics]).to_csv(filename, index=False)

    # --- Save per-class report
    report = classification_report(y_test, y_pred, output_dict=True, zero_division=0)
    pd.DataFrame(report).T.to_csv(filename.replace(".csv", "_PerClass.csv"))

    # --- Save confusion matrices
    cm = confusion_matrix(y_test, y_pred, labels=np.unique(y_test))
    cm_df = pd.DataFrame(cm, index=np.unique(y_test), columns=np.unique(y_test))
    cm_df.to_csv(filename.replace(".csv", "_ConfusionMatrix.csv"))
    cm_norm = cm.astype(float) / cm.sum(axis=1, keepdims=True)
    pd.DataFrame(cm_norm, index=np.unique(y_test), columns=np.unique(y_test)) \
        .to_csv(filename.replace(".csv", "_ConfusionMatrix_Normalized.csv"))

    return metrics


