import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
import os

from sklearn.ensemble import GradientBoostingClassifier
from sklearn.model_selection import StratifiedKFold

# ---- 1) Global reproducibility setup ----
GLOBAL_SEED = 42
np.random.seed(GLOBAL_SEED)
os.environ["PYTHONHASHSEED"] = str(GLOBAL_SEED)

# ---- 2) Load data ----
tpm  = pd.read_csv("Combined_CLR.csv", index_col=0)     # species × samples
meta = pd.read_csv("Metadata_Aligned_to_FilteredMatrix.csv")
common = tpm.columns.intersection(meta["Sample_ID"])
tpm    = tpm[common]
meta   = meta[meta["Sample_ID"].isin(common)].reset_index(drop=True)
tpm    = tpm[meta["Sample_ID"]]   # enforce same order

X = tpm.T.values        # samples × species
y = meta["Group"].values
species = tpm.index.tolist()

print(f"Data loaded: {X.shape[0]} samples × {X.shape[1]} species; groups: {np.unique(y)}")

# ---- 3) Settings & tuned GB params ----
cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=GLOBAL_SEED)
gb_base_params = {
    "n_estimators": 500,
    "learning_rate": 0.1,
    "max_depth": 5,
    "subsample": 0.6,
    "verbose": 0
}


# ---- 4) One-vs-rest training & importance collection ----
env_importances = {env: [] for env in np.unique(y)}

for env in env_importances:
    print(f"\nCollecting importances for environment: {env}")
    y_bin = (y == env).astype(int)

    for fold, (tr_idx, te_idx) in enumerate(cv.split(X, y_bin), 1):
        local_seed = GLOBAL_SEED + fold  # fixed per fold seed
        X_tr, y_tr = X[tr_idx], y_bin[tr_idx]

        gb = GradientBoostingClassifier(random_state=local_seed, **gb_base_params)
        gb.fit(X_tr, y_tr)

        env_importances[env].append(gb.feature_importances_)
        print(f" Fold {fold}/5 done (seed={local_seed})")

# ---- 5) Aggregate mean importances per environment ----
env_mean = {
    env: np.mean(imps, axis=0)
    for env, imps in env_importances.items()
}
env_df = pd.DataFrame(env_mean, index=species)

# ---- 6) Save and visualize ----
topN = 20
for env in env_df.columns:
    top_feats = env_df[env].sort_values(ascending=False).head(topN)
    csv_name = f"Top20_GB_{env}.csv"
    top_feats.to_csv(csv_name, header=["MeanImportance"])
    print(f"Saved top features for {env} to {csv_name}")

    plt.figure(figsize=(6,6))
    sns.barplot(
        x=top_feats.values,
        y=top_feats.index,
        palette="viridis",
        edgecolor="black"
    )
    plt.xlabel("Mean GB Feature Importance", weight="bold")
    plt.ylabel("")
    plt.title(f"Top {topN} Species — {env}", weight="bold")
    sns.despine(left=True, bottom=True)
    plt.tight_layout()
    fig_name = f"Top20_GB_{env}_Barplot.png"
    plt.savefig(fig_name, dpi=300)
    plt.close()
    print(f"Saved barplot for {env} to {fig_name}")

print("\n✅ All per-environment GB feature importance runs completed reproducibly.")

