# ------------------------------------------------------------
# 2. Helper function — evaluation, saving, and AUROC plotting
# ------------------------------------------------------------
def evaluate_and_save(model_name, model, X_train, y_train, X_test, y_test, labels):
    print(f"\n🚀 Evaluating {model_name} on hold-out set...")
    model.fit(X_train, y_train)
    y_pred = model.predict(X_test)

    # ---- Global metrics
    metrics = {
        "Model": model_name,
        "Accuracy": accuracy_score(y_test, y_pred),
        "BalancedAcc": balanced_accuracy_score(y_test, y_pred),
        "F1_macro": f1_score(y_test, y_pred, average="macro"),
        "Kappa": cohen_kappa_score(y_test, y_pred)
    }
    pd.DataFrame([metrics]).to_csv(f"Holdout_metrics_{model_name}.csv", index=False)
    print(f"✅ Global metrics ({model_name}):")
    for k, v in metrics.items():
        if k != "Model":
            print(f"  {k}: {v:.3f}")

    # ---- Per-class report
    report = classification_report(y_test, y_pred, output_dict=True, zero_division=0)
    per_class = (
        pd.DataFrame(report).T
        .loc[[c for c in report.keys() if c in labels]]
        .rename_axis("Class")
        .reset_index()
    )
    per_class.to_csv(f"Holdout_per_class_{model_name}.csv", index=False)

    # ---- Confusion matrices
    cm = confusion_matrix(y_test, y_pred, labels=labels)
    cm_df = pd.DataFrame(cm, index=labels, columns=labels)
    cm_df.to_csv(f"Holdout_confusion_matrix_{model_name}.csv")
    cm_norm = cm.astype(float) / cm.sum(axis=1, keepdims=True)
    cm_norm_df = pd.DataFrame(cm_norm, index=labels, columns=labels)
    cm_norm_df.to_csv(f"Holdout_confusion_matrix_normalized_{model_name}.csv")

    # ---- Confusion Matrix Plot
    plt.figure(figsize=(5, 5))
    sns.heatmap(cm_norm_df, annot=True, fmt=".2f", cmap="Blues",
                cbar=False, square=True, annot_kws={"size": 10})
    plt.title(f"{model_name} — Normalized Confusion Matrix", weight="bold")
    plt.xlabel("Predicted"); plt.ylabel("True")
    plt.tight_layout()
    plt.savefig(f"ConfusionMatrix_{model_name}.png", dpi=300)
    plt.close()

    # ---- AUROC Curves (One-vs-Rest)
    if hasattr(model, "predict_proba"):
        y_bin = label_binarize(y_test, classes=labels)
        y_score = model.predict_proba(X_test)
        plt.figure(figsize=(6, 5))
        for i, cls in enumerate(labels):
            fpr, tpr, _ = roc_curve(y_bin[:, i], y_score[:, i])
            roc_auc = auc(fpr, tpr)
            plt.plot(fpr, tpr, lw=2, label=f"{cls} (AUC = {roc_auc:.2f})")
        plt.plot([0, 1], [0, 1], "--", color="gray", lw=1)
        plt.xlim(0, 1); plt.ylim(0, 1.05)
        plt.xlabel("False Positive Rate"); plt.ylabel("True Positive Rate")
        plt.title(f"{model_name} — One-vs-Rest ROC Curves", weight="bold")
        plt.legend(frameon=False, loc="lower right")
        plt.tight_layout()
        plt.savefig(f"AUROC_{model_name}.png", dpi=300)
        plt.close()
        print(f"✅ AUROC curves saved for {model_name}")
    else:
        print(f"⚠️ {model_name} does not support probability predictions (no AUROC plotted).")

    return metrics


