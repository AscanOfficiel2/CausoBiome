import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns

# If adjustText isn’t installed, use the annotate fallback:
try:
    from adjustText import adjust_text
    use_adjusttext = True
except ImportError:
    use_adjusttext = False

# Load the data
comparison_df = pd.read_csv("Trend_Comparison.csv", index_col=0)
dfc = comparison_df[comparison_df["Consistent_Trend"]].copy()
dfc["Avg_Trend"] = (dfc["External_Trend"].abs() + dfc["Internal_Trend"].abs()) / 2

# Publication style
plt.rcParams.update({
    "font.family": "serif",
    "font.serif": ["Times"],
    "font.size": 12,
    "axes.titlesize": 14,
    "axes.labelsize": 12,
    "xtick.labelsize": 10,
    "ytick.labelsize": 10,
    "axes.linewidth": 2,        # thick axes border
    "xtick.direction": "out",
    "ytick.direction": "out",
})

fig, ax = plt.subplots(figsize=(6,6))

# Scatter
pts = ax.scatter(
    dfc["External_Trend"], dfc["Internal_Trend"],
    s = 100 + 400 * (dfc["Avg_Trend"] / dfc["Avg_Trend"].max()),
    c = dfc["Avg_Trend"], cmap="coolwarm",
    edgecolor="black", linewidth=1.2,
    alpha=0.9
)

# Diagonal (heavier)
lims = [
    min(ax.get_xlim()[0], ax.get_ylim()[0]),
    max(ax.get_xlim()[1], ax.get_ylim()[1])
]
ax.plot(lims, lims, ls="--", lw=2, color="gray", zorder=0)
ax.set_xlim(lims); ax.set_ylim(lims)

# Labels
ax.set_xlabel("External CRC – Control Trend", labelpad=8)
ax.set_ylabel("Internal Case – Control Trend", labelpad=8)
#ax.set_title("Consistent Biomarker Trends", pad=12)

# Colorbar with thick border
