import pandas as pd
import numpy as np
from scipy.stats import mannwhitneyu
import seaborn as sns
import matplotlib.pyplot as plt

# ---------------------- Config ----------------------
external_biomarkers_path = "Filtered_biomarker_annotated.csv"
external_matrix_path     = "Matrix_PRJEB10878_combined_VF_ARG.csv"
external_meta_path       = "PRJEB10878_Metadata_Aligned.csv"
internal_matrix_path     = "combined_ARG_VFDB_final_DATA.csv"
internal_meta_path       = "Metadata_Aligned_VF_ARG_CountMatrix.csv"

external_stats_path      = "External_MannWhitney_Stats.csv"
internal_stats_path      = "Internal_MannWhitney_Stats.csv"
trend_comparison_path    = "Trend_Comparison.csv"
plot_path                = "Barplot_Trend_Comparison.png"

# ---------------------- Load Data ----------------------
external_biomarkers = pd.read_csv(external_biomarkers_path)
external_matrix     = pd.read_csv(external_matrix_path)
external_meta       = pd.read_csv(external_meta_path)

internal_matrix     = pd.read_csv(internal_matrix_path)
internal_meta       = pd.read_csv(internal_meta_path)

# ---------------------- External Prep ----------------------
external_matrix = external_matrix.rename(columns={external_matrix.columns[0]: "Sample_ID"})
features = external_biomarkers["Feature"].tolist()
present_ext = [f for f in features if f in external_matrix.columns]

external_df = external_matrix[["Sample_ID"] + present_ext] \
    .merge(external_meta[["Sample_ID", "Group"]], on="Sample_ID", how="inner")

external_long = external_df.melt(
    id_vars=["Sample_ID", "Group"],
    var_name="Biomarker",
    value_name="Value"
)

# ---------------------- Internal Prep ----------------------
# transpose so samples are rows
internal_t = internal_matrix.set_index(internal_matrix.columns[0]).T.reset_index().rename(columns={"index": "Sample_ID"})
internal_df = internal_t.merge(internal_meta[["Sample_ID", "Group"]], on="Sample_ID", how="inner")

internal_long = internal_df.melt(
    id_vars=["Sample_ID", "Group"],
    var_name="Biomarker",
    value_name="Value"
)
internal_long["Group"] = internal_long["Group"].replace({
    "Cancer": "Case", "Adenoma": "Case", "Healthy": "Control"
})

# ---------------------- Mann-Whitney ----------------------
def mann_whitney_test(df, group_col, value_col, case_label, control_label):
    results = []
    for biomarker, sub in df.groupby("Biomarker"):
        case_vals    = sub[sub[group_col] == case_label][value_col]
        control_vals = sub[sub[group_col] == control_label][value_col]
        if len(case_vals) >= 3 and len(control_vals) >= 3:
            stat, p = mannwhitneyu(case_vals, control_vals, alternative="two-sided")
            results.append((biomarker, stat, p))
    res = pd.DataFrame(results, columns=["Biomarker", "U-statistic", "P-value"])
    res["Adjusted P-value"] = res["P-value"].rank(method="first") / len(res) * 0.05
    return res

external_stats = mann_whitney_test(external_long, "Group", "Value", "CRC", "Control")
internal_filtered = internal_long[internal_long["Biomarker"].isin(features)]
internal_stats    = mann_whitney_test(internal_filtered, "Group", "Value", "Case", "Control")

external_stats.to_csv(external_stats_path, index=False)
internal_stats.to_csv(internal_stats_path, index=False)

# ---------------------- Trend Comparison ----------------------
ext_means = external_long.groupby(["Biomarker", "Group"])["Value"].mean().unstack()
int_means = internal_long.groupby(["Biomarker", "Group"])["Value"].mean().unstack()

common = [b for b in present_ext if b in int_means.index and b in ext_means.index]
comparison_df = pd.DataFrame(index=common)
comparison_df.index.name = "Biomarker"  # ensure reset_index gives correct column

comparison_df["External_CRC"]     = ext_means.loc[common, "CRC"]
comparison_df["External_Control"] = ext_means.loc[common, "Control"]
comparison_df["Internal_Case"]    = int_means.loc[common, "Case"]
comparison_df["Internal_Control"] = int_means.loc[common, "Control"]

comparison_df["External_Trend"]   = comparison_df["External_CRC"] - comparison_df["External_Control"]
comparison_df["Internal_Trend"]   = comparison_df["Internal_Case"] - comparison_df["Internal_Control"]
comparison_df["Consistent_Trend"] = (
    (comparison_df["External_Trend"] > 0) & (comparison_df["Internal_Trend"] > 0)
) | (
    (comparison_df["External_Trend"] < 0) & (comparison_df["Internal_Trend"] < 0)
)

comparison_df.to_csv(trend_comparison_path)

# ---------------------- Prepare bar_df ----------------------
bar_df = comparison_df.reset_index().melt(
    id_vars="Biomarker",
    value_vars=["External_Trend", "Internal_Trend"],
    var_name="Dataset",
    value_name="Trend"
)
bar_df["Dataset"] = bar_df["Dataset"].str.replace("_Trend", "", regex=False)

consistent = comparison_df[comparison_df["Consistent_Trend"]].index.tolist()

# ---------------------- Plot ----------------------
sns.set(style="whitegrid")
plt.figure(figsize=(7, 5))

ax = sns.barplot(
    data=bar_df,
    x="Trend",
    y="Biomarker",
    hue="Dataset",
    edgecolor="black",
    linewidth=2
)

for spine in ax.spines.values():
    spine.set_linewidth(2)
    spine.set_edgecolor("black")

plt.axvline(0, color="black", linestyle="--", linewidth=1.2)
plt.xlabel("Trend (Case/CRC − Control)", fontsize=11)
plt.ylabel("Genes", fontsize=11)
plt.legend(title="Dataset", loc="upper left", frameon=True)

for label in ax.get_yticklabels():
    gene = label.get_text()
    label.set_color("black" if gene in consistent else "black")

plt.tight_layout()
plt.savefig(plot_path, dpi=600)
plt.show()

